"""
backend/app/services/providers/base.py

Abstract base class for LLM providers.
Defines standard interface for asynchronous text generation.
"""

from __future__ import annotations

from abc import ABC, abstractmethod


class LLMProvider(ABC):
    """
    Abstract interface for AI/LLM model providers.
    All providers (Gemini, Groq, etc.) must implement this interface.
    """

    @property
    @abstractmethod
    def name(self) -> str:
        """Provider name identifier (e.g. 'gemini', 'groq')."""
        pass

    @property
    @abstractmethod
    def model_name(self) -> str:
        """Name of the model utilized by this provider."""
        pass

    @abstractmethod
    async def generate(self, prompt: str, system_prompt: str | None = None) -> str:
        """
        Asynchronously generate text completion from the LLM.

        Parameters
        ----------
        prompt : str
            The primary input prompt.
        system_prompt : str | None, optional
            Optional system instruction defining the model persona or format rules.

        Returns
        -------
        str
            The raw text completion generated by the AI model.
        """
        pass

